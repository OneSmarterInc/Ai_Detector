import json
import math
import socket
import tempfile
import textwrap
import unittest
from pathlib import Path
from unittest.mock import patch

from ai_file_inspector.core import detector as ai
from ai_file_inspector.core import scanner as inspector

EXAMPLES = Path(__file__).resolve().parent / "fixtures"


class DetectorTests(unittest.TestCase):
    def test_curly_apostrophes_do_not_inflate_short_text(self):
        result = ai.analyze(("we\u2019re ") * 60)
        self.assertEqual(result["words_in_checked_text"], 60)
        self.assertEqual(result["status"], "not_checked")

    def test_short_text_has_no_score(self):
        r = ai.analyze("This sentence was generated by AI.")
        self.assertEqual(r["status"], "not_checked")
        self.assertNotIn("ai_pattern_score", r)

    def test_disabled_has_no_score(self):
        self.assertEqual(
            ai.analyze("word " * 120, enabled=False)["status"], "not_checked"
        )

    def test_code_is_not_scored(self):
        self.assertEqual(
            ai.analyze("import sys\ndef main():\n return 1\n" * 100)["status"],
            "not_checked",
        )

    def test_other_language_is_not_scored(self):
        r = ai.analyze(
            "यह एक हिंदी वाक्य है और इसे अंग्रेजी भाषा के मॉडल से जांचना सही नहीं है। " * 20
        )
        self.assertEqual(r["status"], "not_checked")
        self.assertNotIn("ai_pattern_score", r)

    def test_french_is_not_scored(self):
        r = ai.analyze(
            "Le jardin est un endroit tranquille où les enfants peuvent jouer pendant que leurs parents préparent le repas. "
            * 10
        )
        self.assertEqual(r["status"], "not_checked")

    def test_cleanup_does_not_edit_original(self):
        original = "**Hello** [garden](https://example.com)\n```print(1)```\nA\u200bB"
        self.assertEqual(ai.clean_prose(original), "Hello garden AB")
        self.assertIn("\u200b", original)

    def test_chunk_limits_and_coverage(self):
        for total in (1, 480, 481, 512, 961, 10000, 100000):
            spans, count = ai.choose_ranges(total)
            self.assertLessEqual(len(spans), 12)
            self.assertEqual(spans[0][1], 0)
            self.assertEqual(spans[-1][2], total)
            self.assertTrue(all(end - start <= 480 for _, start, end in spans))
            self.assertTrue(all(a[2] <= b[1] for a, b in zip(spans, spans[1:])))

    def test_score_rules(self):
        for score, label in (
            (0.1, "Leans human-written"),
            (0.5, "Uncertain"),
            (0.9, "Leans AI-generated"),
        ):
            self.assertEqual(ai.summarize([score], [10])[1], label)

    def test_disagreement_is_uncertain(self):
        self.assertIn("Uncertain", ai.summarize([0.01, 0.99], [100, 100])[1])

    def test_weighted_score(self):
        self.assertAlmostEqual(ai.summarize([0.4, 0.6], [1, 3])[0], 0.55)

    def test_missing_files_are_detected(self):
        with patch.object(ai, "MODEL_DIR", Path("does-not-exist")):
            self.assertFalse(ai.installed())

    def test_class_labels_verified(self):
        config = json.loads((ai.MODEL_DIR / "config.json").read_text())
        self.assertEqual(config["model_type"], "deberta-v2")
        self.assertEqual(len(config["id2label"]), 1)
        self.assertIn(
            "sigmoid", (ai.MODEL_DIR / "README.md").read_text(encoding="utf-8")
        )

    def test_sigmoid_and_extreme_scores(self):
        self.assertEqual(ai.score_logit([[0]]), 0.5)
        self.assertAlmostEqual(ai.score_logit([[math.log(9)]]), 0.9)
        self.assertAlmostEqual(ai.score_logit([[-math.log(9)]]), 0.1)
        self.assertEqual(ai.score_logit([[10000]]), 1)
        self.assertEqual(ai.score_logit([[-10000]]), 0)

    def test_invalid_logits_rejected(self):
        for logits in (
            [[0, 1]],
            [[float("nan")]],
            [[float("inf")]],
            [[float("-inf")]],
            [0],
            [],
        ):
            with self.subTest(logits=logits), self.assertRaises(ValueError):
                ai.score_logit(logits)

    def test_real_inference_is_offline_and_finite(self):
        text = (EXAMPLES / "ai-garden.txt").read_text(encoding="utf-8")
        with patch.object(
            socket.socket,
            "connect",
            side_effect=AssertionError("Network access during inference"),
        ):
            r = ai.analyze(text)
        self.assertEqual(r["status"], "estimated", r)
        self.assertTrue(math.isfinite(r["ai_pattern_score"]))
        self.assertGreaterEqual(r["ai_pattern_score"], 0)
        self.assertLessEqual(r["ai_pattern_score"], 100)

    def test_hidden_marker_does_not_create_ai_score(self):
        text = (EXAMPLES / "ai-garden.txt").read_text(encoding="utf-8")
        a = ai.analyze(text)
        b = ai.analyze(text.replace("garden", "gar\u200bden"))
        self.assertEqual(a["ai_pattern_score"], b["ai_pattern_score"])

    def test_reproducible_inference(self):
        text = (EXAMPLES / "ai-garden.txt").read_text(encoding="utf-8")
        a, b = ai.analyze(text), ai.analyze(text)
        self.assertEqual(a["ai_pattern_score"], b["ai_pattern_score"])

    def test_model_hash_failure_stops_scoring(self):
        with (
            patch.object(ai, "_engine", None),
            patch.object(ai, "MODEL_SHA", "incorrect hash"),
        ):
            with self.assertRaisesRegex(ValueError, "integrity check"):
                ai.get_engine()

    def test_nonfinite_output_is_error_not_human(self):
        from unittest.mock import Mock

        import numpy as np

        engine, tokenizer = ai.get_engine()
        fake = Mock()
        fake.get_inputs.return_value = engine.get_inputs()
        fake.run.return_value = [np.array([[float("nan")]])]
        with patch.object(ai, "get_engine", return_value=(fake, tokenizer)):
            result = ai.analyze((EXAMPLES / "ai-garden.txt").read_text())
        self.assertEqual(result["status"], "error")
        self.assertNotIn("ai_pattern_score", result)

    def test_long_text_sampling_is_reported(self):
        text = (EXAMPLES / "ai-garden.txt").read_text() * 10
        with patch.object(ai, "MAX_PASSAGES", 2):
            result = ai.analyze(text)
        self.assertEqual(result["coverage"], "sampled")
        self.assertEqual(result["passages_checked"], 2)
        self.assertGreater(result["total_passages"], 2)

    def test_word_pdf_and_text_use_same_detector(self):
        from docx import Document
        from reportlab.pdfgen import canvas

        parent = Path(__file__).resolve().parent
        temp = tempfile.TemporaryDirectory(dir=parent)
        root = Path(temp.name)
        try:
            assets = root / "assets"
            assets.mkdir()
            text = (EXAMPLES / "ai-garden.txt").read_text(encoding="utf-8")
            expected = ai.analyze(text)["ai_pattern_score"]
            doc = Document()
            doc.add_paragraph(text)
            doc.save(root / "sample.docx")
            pdf = canvas.Canvas(str(root / "sample.pdf"))
            stream = pdf.beginText(40, 800)
            for line in textwrap.wrap(text, 85):
                stream.textLine(line)
            pdf.drawText(stream)
            pdf.save()
            for name in ("sample.docx", "sample.pdf"):
                with self.subTest(file=name):
                    result = inspector.inspect_file(root / name, assets, [0])
                    self.assertEqual(
                        result["text"]["ai_detection"]["status"], "estimated"
                    )
                    self.assertAlmostEqual(
                        result["text"]["ai_detection"]["ai_pattern_score"],
                        expected,
                        places=1,
                    )
        finally:
            assert root.resolve().parent == parent
            temp.cleanup()

    def test_detector_failure_marks_file_partial(self):
        with patch.object(ai, "get_engine", side_effect=RuntimeError("broken model")):
            result = inspector.inspect_file(EXAMPLES / "ai-garden.txt", EXAMPLES, [0])
        self.assertEqual(result["status"], "partial")

    def test_uncertain_language_has_no_score(self):
        with patch.object(ai, "language", return_value=("en", 0.6)):
            result = ai.analyze((EXAMPLES / "ai-garden.txt").read_text())
        self.assertEqual(result["status"], "not_checked")


if __name__ == "__main__":
    unittest.main(verbosity=2)
